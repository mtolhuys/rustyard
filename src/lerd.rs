use crate::config::Config;
use anyhow::{bail, Context, Result};
use serde::Deserialize;
use std::{collections::HashSet, ffi::OsString, fs, io::Write, path::Path, process::Command};

const MARKER: &str = "# Generated by Rustyard. Local adapter; do not commit this file.\n";

fn executable() -> OsString {
    std::env::var_os("RUSTYARD_LERD").unwrap_or_else(|| "lerd".into())
}

pub fn check_version() -> Result<()> {
    let output = Command::new(executable()).arg("--version").output()
        .context("Lerd is required for domains, HTTPS and supervision. Install/configure Lerd first; Rustyard does not change system settings.")?;
    if !output.status.success() {
        bail!(
            "Lerd --version failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    let version = String::from_utf8_lossy(&output.stdout);
    let supported = version
        .split_whitespace()
        .find_map(|word| {
            let mut parts = word.trim_start_matches('v').split('.');
            let major = parts.next()?.parse::<u32>().ok()?;
            let minor = parts.next()?.parse::<u32>().ok()?;
            Some(major > 1 || (major == 1 && minor >= 24))
        })
        .unwrap_or(false);
    if !supported {
        bail!(
            "Host-proxy support requires Lerd >= 1.24. Found: {}",
            version.trim()
        );
    }
    Ok(())
}

// Single-quote for the shell used by Lerd; JSON encoding below handles YAML separately.
fn shell_quote(value: &str) -> String {
    format!("'{}'", value.replace('\'', "'\"'\"'"))
}

pub fn render(config: &Config, runner: &Path) -> Result<String> {
    let runner = runner
        .to_str()
        .context("Rustyard executable path must be UTF-8 for Lerd")?;
    let command = format!("{} dev", shell_quote(runner));
    let domains = if config.domains.is_empty() {
        String::new()
    } else {
        let entries = config
            .domains
            .iter()
            .map(|domain| format!("  - {domain}\n"))
            .collect::<String>();
        format!("domains:\n{entries}")
    };
    Ok(format!(
        "{MARKER}{domains}secured: true\nproxy:\n  command: {}\n  port: {}\n",
        serde_json::to_string(&command)?,
        config.port
    ))
}

#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
struct Adapter {
    #[serde(default)]
    domains: Vec<String>,
    secured: bool,
    proxy: Proxy,
}

#[derive(Debug, Deserialize, PartialEq)]
#[serde(deny_unknown_fields)]
struct Proxy {
    command: String,
    port: u16,
}

fn adapter_matches(existing: &str, expected: &str, config: &Config) -> Result<bool> {
    let actual: Adapter = serde_yaml::from_str(existing)
        .context("Existing .lerd.yaml has unknown or invalid settings")?;
    let wanted: Adapter = serde_yaml::from_str(expected)?;
    if !actual.secured || actual.proxy != wanted.proxy {
        return Ok(false);
    }
    if config.domains.is_empty() {
        // Lerd adds this explicit primary domain when `link <name>` normalizes
        // a Rustyard adapter that originally relied on the implicit name.
        return Ok(actual.domains.is_empty() || actual.domains == [config.name.as_str()]);
    }
    if config.group.is_none() {
        return Ok(actual.domains == wanted.domains);
    }
    // Grouping replaces the standalone primary before aliases are re-added.
    // An interrupted `up` may therefore have only a safe subset of the
    // declared domains; no unconfigured domain is accepted.
    let allowed: HashSet<&str> = config.domains.iter().map(String::as_str).collect();
    let mut seen = HashSet::new();
    Ok(!actual.domains.is_empty()
        && actual
            .domains
            .iter()
            .all(|domain| allowed.contains(domain.as_str()) && seen.insert(domain.as_str())))
}

pub fn write_adapter(root: &Path, contents: &str, config: &Config) -> Result<()> {
    let path = root.join(".lerd.yaml");
    match fs::read_to_string(&path) {
        Ok(existing) if existing == contents => return Ok(()),
        Ok(existing) if adapter_matches(&existing, contents, config)? => return Ok(()),
        Ok(_) => bail!("Existing .lerd.yaml differs from this adapter (domains, TLS, proxy command/port, or unsupported settings). Nothing was overwritten. Review it before rerunning up."),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {},
        Err(error) => return Err(error.into()),
    }
    let mut file = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&path)?;
    file.write_all(contents.as_bytes())?;
    Ok(())
}

fn output(root: &Path, args: &[&str]) -> Result<std::process::Output> {
    Command::new(executable())
        .args(args)
        .current_dir(root)
        .output()
        .with_context(|| format!("Could not launch Lerd {}", args.join(" ")))
}

/// `None` means this directory has not been linked. Any other backend failure
/// is returned rather than being mistaken for a fresh site.
pub fn domains(root: &Path) -> Result<Option<Vec<String>>> {
    let result = output(root, &["domain", "list"])?;
    if !result.status.success() {
        let error = String::from_utf8_lossy(&result.stderr);
        if error.contains("no site registered for this directory") {
            return Ok(None);
        }
        bail!("Lerd domain list failed: {error}");
    }
    let names = String::from_utf8_lossy(&result.stdout)
        .lines()
        .map(str::trim)
        .filter_map(|line| line.split_whitespace().next())
        .map(str::to_owned)
        .collect::<Vec<_>>();
    if names.is_empty() || names.iter().any(|name| !name.contains('.')) {
        bail!("Lerd domain list returned an unexpected response");
    }
    Ok(Some(names))
}

/// Return the grouped primary domain, or None when this site is not grouped.
/// Refuse an existing, mismatched group instead of moving a site implicitly.
pub fn grouped_primary(root: &Path, config: &Config) -> Result<Option<String>> {
    let group = config
        .group
        .as_ref()
        .context("group configuration is required")?;
    let result = output(root, &["group", "list"])?;
    if !result.status.success() {
        bail!(
            "Lerd group list failed: {}",
            String::from_utf8_lossy(&result.stderr)
        );
    }
    let mut main = None;
    for line in String::from_utf8_lossy(&result.stdout).lines() {
        if !line.starts_with(char::is_whitespace) {
            main = line
                .split_once(" (")
                .map(|(name, domain)| (name.to_owned(), domain.trim_end_matches(')').to_owned()));
            continue;
        }
        if let Some((name, domain)) = line.trim().split_once(" -> ") {
            if name != config.name {
                continue;
            }
            let (main_name, main_domain) = main
                .as_ref()
                .context("Lerd group list returned a secondary without a main")?;
            let expected = format!("{}.{}", group.label, main_domain);
            if main_name != &group.main || domain != expected {
                bail!("Site is grouped as {name} -> {domain} under {main_name}; expected {expected} under {}. Nothing was changed.", group.main);
            }
            return Ok(Some(domain.to_owned()));
        }
    }
    Ok(None)
}

pub fn up_grouped(root: &Path, config: &Config, yes: bool) -> Result<()> {
    let group = config
        .group
        .as_ref()
        .context("group configuration is required")?;
    let linked = domains(root)?.is_some();
    if linked {
        // A no-argument re-link keeps Lerd's grouped primary from .lerd.yaml.
        // An explicit `link <name>` would force the standalone alias to primary.
        if root.file_name().and_then(|s| s.to_str()) != Some(config.name.as_str()) {
            bail!("Grouped Rustyard sites need a project directory named {} to preserve the primary domain on repeated up", config.name);
        }
        if yes {
            run(root, &["link", "--yes"])?;
        } else {
            run(root, &["link"])?;
        }
    } else {
        let mut args = vec!["link", config.name.as_str()];
        if yes {
            args.push("--yes");
        }
        run(root, &args)?;
    }
    if grouped_primary(root, config)?.is_none() {
        run(root, &["group", "add", &group.main, &group.label])?;
    }
    let primary =
        grouped_primary(root, config)?.context("Lerd did not register the requested site group")?;
    let stem = &config.domains[0];
    let tld = primary
        .strip_prefix(&format!("{stem}."))
        .filter(|suffix| !suffix.is_empty() && !suffix.contains('.'))
        .context("Grouped primary domain does not match the portable Rustyard domain")?;
    let mut current = domains(root)?.context("Lerd lost the site registration")?;
    for alias in config.domains.iter().skip(1) {
        let full = format!("{alias}.{tld}");
        if !current.contains(&full) {
            run(root, &["domain", "add", alias])?;
            current = domains(root)?.context("Lerd lost the site registration")?;
        }
    }
    let expected = config
        .domains
        .iter()
        .map(|domain| format!("{domain}.{tld}"))
        .collect::<Vec<_>>();
    if current != expected {
        bail!("Lerd registered unexpected domains {current:?}; expected {expected:?}. Review the group and aliases before continuing.");
    }
    let rendered = render(config, &std::env::current_exe()?)?;
    write_adapter(root, &rendered, config)?;
    Ok(())
}

pub fn run(root: &Path, args: &[&str]) -> Result<()> {
    let status = Command::new(executable())
        .args(args)
        .current_dir(root)
        .status()
        .context("Could not launch Lerd")?;
    if !status.success() {
        bail!("Lerd {} failed ({status}). See its output above; the operation may be partially applied.", args.join(" "));
    }
    Ok(())
}

pub fn logs(root: &Path, name: &str, follow: bool, lines: u32) -> Result<()> {
    if std::env::consts::OS == "macos" {
        println!("Open the site's Dev Server tab for application logs.");
        return run(root, &["dashboard"]);
    }
    let mut command = Command::new("journalctl");
    command.args([
        "--user",
        "--unit",
        &format!("lerd-app-{name}"),
        "--lines",
        &lines.to_string(),
        "--no-pager",
    ]);
    if follow {
        command.arg("--follow");
    }
    if !command
        .status()
        .context("Cannot read app logs with journalctl")?
        .success()
    {
        bail!("Reading app logs failed. Use the Dev Server tab in `rustyard dashboard`.");
    }
    Ok(())
}

pub fn doctor(root: &Path) -> Result<()> {
    let output = Command::new(executable())
        .arg("doctor")
        .current_dir(root)
        .output()
        .context("Could not run Lerd infrastructure checks")?;
    let stdout = String::from_utf8_lossy(&output.stdout);
    print!("{stdout}");
    eprint!("{}", String::from_utf8_lossy(&output.stderr));
    // Lerd 1.33 reports failed diagnostics but still exits zero.
    let reported_failure = stdout.lines().any(|line| {
        line.trim_start().starts_with('✗')
            || (line.contains(" failure")
                && line
                    .split_whitespace()
                    .next()
                    .and_then(|count| count.parse::<u32>().ok())
                    .is_some_and(|count| count > 0))
    });
    if !output.status.success() || reported_failure {
        bail!("Lerd infrastructure checks failed. See the diagnostics above; run these checks on the host if your session restricts sockets or user services.");
    }
    Ok(())
}

#[cfg(all(test, unix))]
mod tests {
    use super::*;
    use crate::config::Group;
    use std::os::unix::fs::PermissionsExt;

    fn sample_config() -> Config {
        Config {
            name: "acme".into(),
            port: 3020,
            command: vec!["cargo".into(), "run".into()],
            watch: vec!["src".into()],
            domains: Vec::new(),
            group: None,
        }
    }

    #[test]
    fn adapter_command_executes_literal_paths_with_spaces_quotes_and_shell_metacharacters(
    ) -> Result<()> {
        let dir = tempfile::tempdir()?;
        let runner = dir
            .path()
            .join("runner 'quoted' $(touch injected) with spaces");
        fs::write(&runner, "#!/bin/sh\nprintf '%s' \"$1\" > invoked\n")?;
        fs::set_permissions(&runner, fs::Permissions::from_mode(0o700))?;
        let config = Config {
            name: "app".into(),
            port: 3100,
            ..sample_config()
        };
        let rendered = render(&config, &runner)?;
        let line = rendered
            .lines()
            .find_map(|line| line.strip_prefix("  command: "))
            .unwrap();
        let command: String = serde_json::from_str(line)?;
        let status = Command::new("sh")
            .args(["-c", &command])
            .current_dir(dir.path())
            .status()?;
        assert!(status.success());
        assert_eq!(fs::read_to_string(dir.path().join("invoked"))?, "dev");
        assert!(!dir.path().join("injected").exists());
        Ok(())
    }

    #[test]
    fn accepts_backend_yaml_normalization_but_rejects_proxy_drift_and_unknown_settings(
    ) -> Result<()> {
        let dir = tempfile::tempdir()?;
        let config = sample_config();
        let runner = Path::new("/home/example/.local/bin/rustyard");
        let expected = render(&config, runner)?;
        let normalized = "domains:\n  - acme\nsecured: true\nproxy:\n  command: '''/home/example/.local/bin/rustyard'' dev'\n  port: 3020\n";
        fs::write(dir.path().join(".lerd.yaml"), normalized)?;
        write_adapter(dir.path(), &expected, &config)?;
        assert_eq!(
            fs::read_to_string(dir.path().join(".lerd.yaml"))?,
            normalized
        );

        for drift in [
            normalized.replace("rustyard'' dev", "rustyard'' dev --other"),
            normalized.replace("port: 3020", "port: 3021"),
            format!(
                "{normalized}custom_workers:\n  unsafe: {{command: 'echo unsafe', host: true}}\n"
            ),
            normalized.replace("acme", "other-company"),
        ] {
            fs::write(dir.path().join(".lerd.yaml"), &drift)?;
            assert!(write_adapter(dir.path(), &expected, &config).is_err());
            assert_eq!(fs::read_to_string(dir.path().join(".lerd.yaml"))?, drift);
        }
        Ok(())
    }

    #[test]
    fn grouped_adapter_accepts_only_declared_domains_during_backend_transitions() -> Result<()> {
        let mut config = sample_config();
        config.name = "shop".into();
        config.port = 3010;
        config.domains = vec!["shop.acme".into(), "shop".into()];
        config.group = Some(Group {
            main: "acme".into(),
            label: "shop".into(),
        });
        config.validate()?;
        let expected = render(&config, Path::new("/home/example/.local/bin/rustyard"))?;
        let dir = tempfile::tempdir()?;
        for domains in ["  - shop\n", "  - shop.acme\n", "  - shop.acme\n  - shop\n"] {
            let adapter = expected.replace("  - shop.acme\n  - shop\n", domains);
            fs::write(dir.path().join(".lerd.yaml"), adapter)?;
            write_adapter(dir.path(), &expected, &config)?;
        }
        let foreign = expected.replace("  - shop\n", "  - unrelated\n");
        fs::write(dir.path().join(".lerd.yaml"), foreign)?;
        assert!(write_adapter(dir.path(), &expected, &config).is_err());
        Ok(())
    }
}
